import type { ResolvedToken } from "./system-types.ts";
import type { CompileInput } from "./tokens-compile.ts";
import { namespaceOf, norm, tailwindNames } from "./tokens-tailwind.ts";

const GROUP_UTILITY: Record<string, string> = {
    bg: "bg",
    background: "bg",
    text: "text",
    fg: "text",
    foreground: "text",
    border: "border",
    outline: "outline",
    ring: "ring",
    fill: "fill",
    stroke: "stroke",
};

function utilitiesOf(token: ResolvedToken, variable: string): string {
    const namespace = namespaceOf(variable);

    if (namespace === undefined) {
        return `no utility: \`var(${variable})\``;
    }

    const rest = variable.slice(namespace.length + 3);
    const one = (prefix: string) => `\`${prefix}-${rest}\``;

    switch (namespace) {
        case "color": {
            // Only the group of the role says which utility it is for (`color.bg.*`); `color.accent.fill` is not for `fill-`.
            const word = GROUP_UTILITY[norm(token.path[1] ?? "")];

            return word !== undefined && token.path.length > 2
                ? one(word)
                : ["bg", "text", "border"].map(one).join(" ");
        }

        case "font":
        case "font-weight":
            return one("font");
        case "spacing":
            return ["p", "m", "gap"].map(one).join(" ");
        case "radius":
            return one("rounded");
        case "breakpoint":
            return `\`${rest}:\``;
        case "container":
            return `${one("max-w")} \`@${rest}:\``;
        default:
            return one(namespace);
    }
}

const cell = (text: string) => text.replace(/\|/g, "\\|");

export function namesMarkdown(system: CompileInput): string {
    const names = tailwindNames(system);
    const groups = new Map<string, ResolvedToken[]>();

    for (const token of system.tokens) {
        const group = token.path[0]!;

        groups.set(group, [...(groups.get(group) ?? []), token]);
    }

    const lines = [
        `# Names: ${system.name}`,
        "",
        "Generated by Pi Pocket from `.pi/design/`. Do not edit by hand: change the tokens, then compile again.",
        "",
        "Each token has a name in three places: the variable in `tokens.css`, the variable in `tailwind.css`, and the utilities that Tailwind makes from that variable. Use the variable in CSS (`var(--color-bg-surface)`) and the class in Tailwind markup (`bg-surface`).",
        "",
        "## How the names come out",
        "",
        "- **`tokens.css`**: the path of the token joined by `-`, with `--` in front. `color.bg.surface` is `--color-bg-surface`. Nothing else is added or dropped.",
        "- **`tailwind.css`**: the variable is in the namespace of Tailwind v4 that fits the kind of the token, so that Tailwind makes the right utilities: `--color-*`, `--font-*` (families), `--text-*`, `--font-weight-*`, `--tracking-*`, `--leading-*`, `--breakpoint-*`, `--container-*`, `--spacing-*`, `--radius-*`, `--shadow-*`, `--inset-shadow-*`, `--drop-shadow-*`, `--blur-*`, `--perspective-*`, `--aspect-*`, `--ease-*`. A token that fits none keeps its `tokens.css` name (`--button-height`), and one whose name would be read as a namespace of another kind gets `--ds-` in front.",
        "- **Color roles** drop the word that the utility already says: `color.bg.surface` is `--color-surface`, so the class is `bg-surface`, not `bg-bg-surface`; `color.text.muted` is `text-muted`; `color.border.subtle` is `border-subtle`.",
        "- **A role that is only `default`, `primary`, `secondary`, `tertiary`, `base`, `main`, `normal`, `regular`, or `standard`** says nothing alone (`primary` is also the brand), so it takes the word of its group: `color.border.default` is `--color-border`, `color.text.primary` is `--color-text`, `color.bg.base` is `--color-bg`. Outside those groups a trailing `default` goes: `color.accent.default` is `--color-accent`.",
        "- **Two tokens that want one name**: the first in the file keeps it, and the other keeps its full name (`color.text.secondary` is `--color-text-secondary`).",
        "- Every color makes `bg-`, `text-`, `border-`, `ring-`, `fill-`, and `stroke-` utilities. The table shows the one that the group of the role names; the others work too.",
        "",
    ];

    for (const [group, tokens] of groups) {
        lines.push(
            `## ${group}`,
            "",
            "| Token | `tokens.css` | `tailwind.css` | Utilities |",
            "| --- | --- | --- | --- |",
        );

        for (const token of tokens) {
            const variable = names.get(token.name) ?? token.cssVar;

            lines.push(
                `| \`${cell(token.name)}\` | \`${cell(token.cssVar)}\` | \`${cell(variable)}\` | ${cell(utilitiesOf(token, variable))} |`,
            );
        }

        lines.push("");
    }

    return `${lines.join("\n").trimEnd()}\n`;
}
